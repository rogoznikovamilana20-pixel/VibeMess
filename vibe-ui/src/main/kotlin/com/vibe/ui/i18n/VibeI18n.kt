object VibeI18n {

    var currentCode: String by mutableStateOf("ru")
        private set

    fun setLanguage(code: String) {
        currentCode = if (code in VibeLanguages.byCode) code else "en"
    }

    private val fallbackChain: List<String> get() = listOf(currentCode, "en")

    fun t(key: String): String {
        for (lang in fallbackChain) {
            val value = dict[lang]?.get(key)
            if (value != null) return value
        }
        return key
    }

    private val dict: Map<String, Map<String, String>> = buildDict()
}

